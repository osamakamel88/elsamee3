def search_arab_cmo_directory(query: str) -> List[Dict[str, Any]]:
    """Search the Arab Copyright Societies, author databases, and registries."""
    q = query.strip().lower()
    if not q:
        return ARAB_CMO_DATABASE

    results = []
    for item in ARAB_CMO_DATABASE:
        searchable_text = f"{item['title']} {item['country']} {item['description']} {item['author']}".lower()
        if q in searchable_text:
            results.append(item)
    return results
